"""Ready-made questionnaires that are not standardised instruments.

Unlike NPS / CSAT / CES / SUS / UEQ (fixed wording in ``survey_templates``), these are
ordinary editable drafts: they carry no methodology tag, so nothing is claimed about
comparability of results. Wording is neutral and avoids leading the respondent.
"""

from __future__ import annotations

from typing import Any, Callable


def _radio(label: str, options: list[str], *, required: bool = True) -> dict[str, Any]:
    return {
        "type": "radio",
        "label": label,
        "placeholder": None,
        "required": required,
        "options": [{"label": option} for option in options],
        "config": {},
    }


def _checkbox(label: str, options: list[str], *, required: bool = False) -> dict[str, Any]:
    return {**_radio(label, options, required=required), "type": "checkbox"}


def _rating(label: str, left: str, right: str, *, max_: int = 5, required: bool = True) -> dict[str, Any]:
    return {
        "type": "rating",
        "label": label,
        "placeholder": None,
        "required": required,
        "config": {
            "ratingVariant": "numeric_scale",
            "min": 1,
            "max": max_,
            "step": 1,
            "leftLabel": left,
            "rightLabel": right,
        },
    }


def _text(label: str, *, required: bool = False) -> dict[str, Any]:
    return {"type": "longText", "label": label, "placeholder": None, "required": required, "config": {}}


def usability() -> list[dict[str, Any]]:
    return [
        _radio(
            "Удалось ли вам выполнить задачу, ради которой вы открыли продукт?",
            ["Да, без затруднений", "Да, но с трудностями", "Нет, не удалось", "Я не пытался(ась) её выполнить"],
        ),
        _rating("Насколько понятен интерфейс?", "Совсем не понятен", "Полностью понятен"),
        _checkbox(
            "С какими трудностями вы столкнулись?",
            [
                "Не нашёл(ла) нужную функцию",
                "Непонятные названия и подписи",
                "Слишком много шагов",
                "Медленная работа",
                "Ошибки и сбои",
                "Трудностей не было",
            ],
        ),
        _text("Что бы вы изменили в первую очередь?"),
        _text("Что вы ожидали увидеть, но не нашли?"),
    ]


