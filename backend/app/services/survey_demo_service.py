_UNSUPPORTED = {"address", "address_country_city", "location"}


def _config(field: dict[str, Any]) -> dict[str, Any]:
    config = field.get("config")
    return config if isinstance(config, dict) else {}


def _number(value: Any, default: float) -> float:
    return float(value) if isinstance(value, (int, float)) and not isinstance(value, bool) else default


def _option_ids(field: dict[str, Any]) -> list[tuple[str, bool]]:
    """(option id, is it the «Другое» option) in form order."""
    return [
        (o["id"], bool(o.get("isOther")))
        for o in field.get("options") or []
        if isinstance(o, dict) and isinstance(o.get("id"), str)
    ]


def _option_profiles(fields: list[dict[str, Any]], rng: random.Random) -> dict[str, list[float]]:
    """A popularity weight per option, fixed for the whole run, so the options do not tie.

    Squaring a random number gives a few clear leaders and a tail — like real answers.
    """
    return {
        f["id"]: [rng.random() ** 2 + 0.1 for _ in _option_ids(f)]
        for f in fields
        if f.get("type") in {"radio", "dropdown", "checkbox"}
    }


def _other_value(rng: random.Random) -> str:
    return OTHER_PREFIX + rng.choice(OTHER_TEXTS)


def _pick_option(field: dict[str, Any], weights: list[float], rng: random.Random) -> str:
    option_id, is_other = rng.choices(_option_ids(field), weights=weights, k=1)[0]
    return _other_value(rng) if is_other else option_id


def _pick_options(field: dict[str, Any], weights: list[float], rng: random.Random) -> list[str]:
    options = _option_ids(field)
    wanted = min(len(options), rng.choice([1, 1, 2, 2, 3]))
    pool = list(zip(options, weights))
    chosen: list[str] = []
    for _ in range(wanted):
        picked = rng.choices(pool, weights=[w for _, w in pool], k=1)[0]
        pool.remove(picked)
        (option_id, is_other), _weight = picked
        chosen.append(_other_value(rng) if is_other else option_id)
    return chosen


def _rating(field: dict[str, Any], rng: random.Random) -> dict[str, Any]:
    config = _config(field)
    low = _number(config.get("min"), 1)
    high = _number(config.get("max"), 5)
    if high <= low:
        low, high = 1.0, 5.0
    step = _number(config.get("step"), 1) or 1
    # Most people rate a little above the middle
    raw = rng.gauss(low + 0.7 * (high - low), (high - low) * 0.22)
    snapped = low + round((min(max(raw, low), high) - low) / step) * step
    value = min(max(snapped, low), high)

    def plain(number: float) -> int | float:
        return int(number) if float(number).is_integer() else number

    return {"value": plain(value), "min": plain(low), "max": plain(high)}


def _number_answer(field: dict[str, Any], rng: random.Random) -> int:
    config = _config(field)
    low = _number(config.get("min"), 0)
    high = _number(config.get("max"), 100)
    if high <= low:
        low, high = 0.0, 100.0
    return rng.randint(int(low), int(high))


def _attention_answer(field: dict[str, Any]) -> Any | None:
    """The right answer of an attention check, so generated responses are not flagged for it."""
    config = _config(field)
    if not config.get("attentionCheck"):
        return None
    correct = config.get("attentionCorrect")
    if not isinstance(correct, str):
        return None
    for option in field.get("options") or []:
        if not isinstance(option, dict) or not isinstance(option.get("id"), str):
            continue
        if str(option.get("label", "")).strip().lower() == correct.strip().lower():
            return [option["id"]] if field.get("type") == "checkbox" else option["id"]
    return None


def _answer(
    field: dict[str, Any],
    profiles: dict[str, list[float]],
    rng: random.Random,
    respondent_no: int,
    now: datetime,
) -> Any | None:
    """One answer in the shape the web form stores it; None when the type is not generated."""
    kind = field.get("type")
    attention = _attention_answer(field)
    if attention is not None:
        return attention
    if kind in {"radio", "dropdown"}:
        return _pick_option(field, profiles[field["id"]], rng) if _option_ids(field) else None
    if kind == "checkbox":
        return _pick_options(field, profiles[field["id"]], rng) if _option_ids(field) else None
    if kind == "yesNo":
        return "yes" if rng.random() < YES_RATE else "no"
    if kind == "rating":
        return _rating(field, rng)
    if kind == "number":
        return _number_answer(field, rng)
    if kind == "longText":
        return rng.choice(LONG_TEXTS)
    if kind == "shortText":
        return rng.choice(SHORT_TEXTS)
    if kind == "fullName":
        return rng.choice(FAKE_NAMES)
    if kind == "email":
        return f"demo{respondent_no}@example.com"
    if kind == "phone":
        return f"+7 900 000-00-{respondent_no % 100:02d}"
    moment = now - timedelta(days=rng.randint(0, 30), minutes=rng.randint(0, 1439))
    if kind == "date":
        return moment.strftime("%Y-%m-%d")
    if kind == "dateTime":
        return moment.strftime("%Y-%m-%dT%H:%M")
    if kind == "time":
        return moment.strftime("%H:%M")
    return None


def generate_answers(
    pages: Any,
    rng: random.Random,
    *,
    respondent_no: int,
    profiles: dict[str, list[float]] | None = None,
    now: datetime | None = None,
) -> dict[str, Any]:
    """Answers of one made-up respondent; required questions are always answered."""
    fields = survey_answers.answerable_fields(pages)
    profiles = profiles if profiles is not None else _option_profiles(fields, rng)
    now = now or datetime.now(timezone.utc)
    answers: dict[str, Any] = {}
    for field in fields:
        # An attention check left empty counts as failed, so it is answered like a required question
        skippable = not field.get("required") and _attention_answer(field) is None
        if skippable and rng.random() > OPTIONAL_ANSWER_RATE:
            continue
        value = _answer(field, profiles, rng, respondent_no, now)
        if value is not None:
            answers[field["id"]] = value
    if not answers:
        # A response without a single answer is not a response: take the first question that can be answered
        for field in fields:
            value = _answer(field, profiles, rng, respondent_no, now)
            if value is not None:
                answers[field["id"]] = value
                break
    return answers


def _duration(questions: int, rng: random.Random) -> int:
    """Seconds a person would spend; clear of the «too fast» threshold."""
    return rng.randint(int(questions * 5) + 25, int(questions * 14) + 90)


def build_responses(
    survey: Survey, count: int, rng: random.Random | None = None, now: datetime | None = None
) -> list[SurveyResponse]:
    """The responses (not saved) for the survey's current form."""
    rng = rng or random.Random()
    now = now or datetime.now(timezone.utc)
    pages = survey.pages if isinstance(survey.pages, list) else []
    fields = survey_answers.answerable_fields(pages)
    unsupported = [
        f for f in fields if f.get("type") in _UNSUPPORTED or str(f.get("type")).startswith("file_")
    ]
    if any(f.get("required") for f in unsupported):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="demo_unsupported_required"
        )

    profiles = _option_profiles(fields, rng)
    window_start = max(survey.created_at, now - timedelta(days=SPREAD_DAYS))
    window = max((now - window_start).total_seconds(), 60.0)

    responses: list[SurveyResponse] = []
    for number in range(1, count + 1):
        raw = generate_answers(pages, rng, respondent_no=number, profiles=profiles, now=now)
        try:
            answers = survey_answers.validate_answers(pages, raw)
        except survey_answers.AnswersError as exc:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail={"code": exc.code, "missing": exc.missing},
            ) from exc
        if not answers:
            continue
        duration = _duration(len(fields), rng)
        responses.append(
            SurveyResponse(
                survey_id=survey.id,
                answers=answers,
                schema_snapshot=pages,
                quality_flags=survey_quality.detect_flags(pages, answers, duration),
                respondent_meta={"demo": True},
                duration_seconds=duration,
                submitted_at=now - timedelta(seconds=rng.uniform(0, window)),
            )
        )
    return responses


async def add_demo_responses(
    session: AsyncSession, user: User, survey_id: str, count: int
) -> DemoResponsesResult:
    survey = await _get_for_member(session, survey_id, user)
    if survey.status not in ("open", "closed"):
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="survey_not_published")
    # Test answers go only to a survey nobody has answered: they must never mix with real data
    # Responses kept back by the quota are real answers too
    if await survey_repository.count_responses(session, survey.id, include_locked=True) > 0:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="survey_has_responses")

    responses = build_responses(survey, count)
    for response in responses:
        await survey_repository.add_response(session, response)
    await session.commit()
    return DemoResponsesResult(created=len(responses))


async def remove_demo_responses(
    session: AsyncSession, user: User, survey_id: str
) -> DemoResponsesRemoved:
    survey = await _get_for_member(session, survey_id, user)
    removed = await survey_repository.delete_demo_responses(session, survey.id)
    if removed:
        # A summary written from test answers says nothing about the real ones
        survey.ai_summary = None
    await session.commit()
    return DemoResponsesRemoved(removed=removed)
