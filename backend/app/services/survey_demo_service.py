"""Test answers for the guided tour: a believable set of responses made from the survey's own form.

The answers are generated by rules (no AI): free and predictable, and they do not depend on an
external service. Every generated response carries ``respondent_meta = {"demo": true}``, so it can
be told from a real one and removed again.
"""

