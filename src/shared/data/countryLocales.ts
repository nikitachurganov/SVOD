const DEFAULT_LOCALE = 'en';

export const getCountryCityLocale = (iso2: string): string =>
  COUNTRY_LOCALE_OVERRIDES[iso2.toUpperCase()] ?? DEFAULT_LOCALE;

export const getCitySortLocale = (iso2: string): string => {
  const locale = getCountryCityLocale(iso2);
  if (locale === 'zh-CN') return 'zh';
  if (locale === 'jp') return 'ja';
  return locale;
};
